//! Generate tiny nextest corpus stubs from local JSONL metallib shards.
//!
//! Output is gitignored (`validation/tests/corpus_NN.rs`). Each stub holds only
//! `(shard, byte_offset, byte_len)` and calls [`metal2vulkan_validation::run_corpus_case`].
//!
//! Usage (from repo root):
//!   cargo run -p metal2vulkan-validation --bin metallib_gen_tests
//!   cargo run -p metal2vulkan-validation --bin metallib_gen_tests -- /path/to/corpus/local
//!
//! Default corpus dir: `$METAL2VULKAN_CORPUS_DIR` or `validation/corpus/local`.

use serde::Deserialize;
use std::collections::HashMap;
use std::fs::{self, File};
use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};

const SHARD_COUNT: usize = 16;

#[derive(Debug, Deserialize)]
struct StubRecord {
    hash: String,
    #[serde(rename = "fn")]
    fn_name: Option<String>,
    #[serde(default)]
    synth: bool,
    ignore_reason: Option<String>,
    #[serde(default)]
    air_ll: String,
}

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let corpus_dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("METAL2VULKAN_CORPUS_DIR").map(PathBuf::from))
        .unwrap_or_else(|| manifest_dir.join("corpus/local"));
    let tests_dir = manifest_dir.join("tests");
    fs::create_dir_all(&tests_dir)
        .unwrap_or_else(|e| panic!("create {}: {e}", tests_dir.display()));

    let harness_skip = load_harness_skip(&corpus_dir);
    // Committed broken.jsonl: bake #[ignore] so cargo test won't even enter run_corpus_case.
    let broken = metal2vulkan_validation::load_broken();
    let mut any = false;
    for shard in 0..SHARD_COUNT {
        if generate_shard(&corpus_dir, &tests_dir, shard, &harness_skip, &broken) {
            any = true;
        }
    }
    if !any {
        eprintln!(
            "metallib_gen_tests: no shard_NN.jsonl under {}/shards — nothing generated",
            corpus_dir.display()
        );
        eprintln!("see validation/corpus/README.md");
        std::process::exit(2);
    }
}

fn load_harness_skip(corpus_dir: &Path) -> HashMap<String, String> {
    #[derive(Deserialize)]
    struct SkipRecord {
        hash: String,
        reason: String,
    }
    let path = corpus_dir.join("harness_skip.jsonl");
    let text = match fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return HashMap::new(),
        Err(e) => panic!("read {}: {e}", path.display()),
    };
    text.lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| {
            let record: SkipRecord = serde_json::from_str(line)
                .unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));
            (record.hash, record.reason)
        })
        .collect()
}

/// Returns true if a shard file existed and was written.
fn generate_shard(
    corpus_dir: &Path,
    tests_dir: &Path,
    shard: usize,
    harness_skip: &HashMap<String, String>,
    broken: &metal2vulkan_validation::BrokenIndex,
) -> bool {
    let shard_id = format!("{shard:02}");
    let input_path = corpus_dir
        .join("shards")
        .join(format!("shard_{shard_id}.jsonl"));
    // Also accept flat layout: corpus/local/shard_00.jsonl (monorepo drop-in).
    let input_path = if input_path.is_file() {
        input_path
    } else {
        let flat = corpus_dir.join(format!("shard_{shard_id}.jsonl"));
        if flat.is_file() {
            flat
        } else {
            return false;
        }
    };

    let input =
        File::open(&input_path).unwrap_or_else(|e| panic!("open {}: {e}", input_path.display()));
    let mut reader = BufReader::new(input);
    let output_path = tests_dir.join(format!("corpus_{shard_id}.rs"));
    let mut output = String::new();
    output.push_str("// @generated by metallib_gen_tests. Do not edit by hand.\n");
    output.push_str("// gitignored private corpus stubs — see validation/corpus/README.md\n");
    output.push_str("#![allow(non_snake_case)]\n\n");

    let mut offset = 0u64;
    let mut row = 0usize;
    let mut names = HashMap::<String, usize>::new();
    let mut line = Vec::new();
    loop {
        line.clear();
        let read = reader
            .read_until(b'\n', &mut line)
            .unwrap_or_else(|e| panic!("read {}: {e}", input_path.display()));
        if read == 0 {
            break;
        }
        let json_len = trim_line_ending_len(&line);
        if json_len != 0 {
            let record: StubRecord = serde_json::from_slice(&line[..json_len])
                .unwrap_or_else(|e| panic!("parse {} row {}: {e}", input_path.display(), row + 1));
            write_stub(
                &mut output,
                &shard_id,
                offset,
                json_len,
                &record,
                &mut names,
                harness_skip,
                broken,
            );
            row += 1;
        }
        offset += read as u64;
    }

    let mut file = File::create(&output_path)
        .unwrap_or_else(|e| panic!("create {}: {e}", output_path.display()));
    file.write_all(output.as_bytes())
        .unwrap_or_else(|e| panic!("write {}: {e}", output_path.display()));
    eprintln!("generated {row} rows into {}", output_path.display());
    true
}

#[allow(clippy::too_many_arguments)]
fn write_stub(
    output: &mut String,
    shard_id: &str,
    offset: u64,
    len: usize,
    record: &StubRecord,
    names: &mut HashMap<String, usize>,
    harness_skip: &HashMap<String, String>,
    broken: &metal2vulkan_validation::BrokenIndex,
) {
    let base_name = format!("c_{}", record.hash);
    let seen = names.entry(base_name.clone()).or_insert(0);
    let name = if *seen == 0 {
        base_name
    } else {
        format!("{base_name}_{}", *seen)
    };
    *seen += 1;

    output.push_str("#[test]\n");
    if let Some(reason) = harness_skip.get(&record.hash) {
        output.push_str(&format!("#[ignore = {reason:?}]\n"));
    } else if let Some(entry) = broken_for_record(record, broken) {
        let reason = format!("broken: {}", entry.reason);
        output.push_str(&format!("#[ignore = {reason:?}]\n"));
    } else if let Some(reason) = stub_ignore_reason(record) {
        output.push_str(&format!("#[ignore = {reason:?}]\n"));
    }
    output.push_str(&format!(
        "fn {name}() {{\n    metal2vulkan_validation::run_corpus_case({shard_id:?}, {offset}, {len});\n}}\n\n"
    ));
}

fn broken_for_record<'a>(
    record: &StubRecord,
    broken: &'a metal2vulkan_validation::BrokenIndex,
) -> Option<&'a metal2vulkan_validation::BrokenEntry> {
    if record.air_ll.is_empty() {
        return None;
    }
    let air_sha = metal2vulkan_validation::air_sha256_hex(record.air_ll.as_bytes());
    broken.entries.get(&air_sha)
}

fn stub_ignore_reason(record: &StubRecord) -> Option<String> {
    if !record.synth {
        return Some(
            record
                .ignore_reason
                .clone()
                .unwrap_or_else(|| "metallib: not synthesized".into()),
        );
    }
    let fn_name = record.fn_name.as_deref().unwrap_or("");
    if fn_name.starts_with("argmin_") || fn_name.starts_with("argmax_") {
        return Some(
            "metallib: oracle runtime hazard: MLX argmin/argmax reductions exceed foreground test budget"
                .into(),
        );
    }
    if record.air_ll.contains("!\"air.visible_function_table\"") {
        return Some(
            "metallib: harness gap: visible function tables are not synthesized or bound".into(),
        );
    }
    if record.air_ll.contains("air.intersect.") {
        return Some(
            "metallib: harness gap: Metal intersector resources are not synthesized".into(),
        );
    }
    if record.air_ll.contains("implicit_imageblock") {
        return Some(
            "metallib: oracle pipeline gap: implicit imageblock kernels need tile/render context"
                .into(),
        );
    }
    None
}

fn trim_line_ending_len(line: &[u8]) -> usize {
    let mut len = line.len();
    if len != 0 && line[len - 1] == b'\n' {
        len -= 1;
    }
    if len != 0 && line[len - 1] == b'\r' {
        len -= 1;
    }
    len
}
